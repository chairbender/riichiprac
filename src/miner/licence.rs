//! Licence metadata and the fail-closed licence gate.
//!
//! Both AI engines and generated data carry a licence. The miner records the
//! exact id, attribution, commercial-use flag and source URL, and rejects an
//! unknown id rather than guessing. The pack publisher later intersects the
//! flags of every contributing agent; [`data_commercial_use_all`] implements
//! that logical AND.

use serde::{Deserialize, Serialize};
use thiserror::Error;

/// Data licences we may publish a pack under.
///
/// The engine licences (`AGPL-3.0`, `akochan-custom`) are valid *agent*
/// licences but are not valid data licences for a shipped pack.
pub const ALLOWED_DATA_LICENCES: &[&str] = &["CC-BY-4.0", "CC0-1.0", "MIT"];

/// Every licence id the miner recognises, for agent records and pack data.
pub const KNOWN_LICENCES: &[&str] = &["CC-BY-4.0", "CC0-1.0", "MIT", "AGPL-3.0", "akochan-custom"];

/// Licence metadata attached to an agent or a generated log.
///
/// `data_commercial_use` describes the generated game records, not the engine
/// code: an AGPL engine can still produce data we publish, while Akochan
/// output is non-commercial with attribution.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LicenseInfo {
    /// Stable licence id from [`KNOWN_LICENCES`], for example `AGPL-3.0`.
    pub id: String,
    /// Human-readable credit, including the model/version where applicable.
    pub attribution: String,
    /// Whether the generated data may be used commercially.
    pub data_commercial_use: bool,
    /// Where the licence text/terms came from.
    ///
    /// Required by the ingest gate so a row can be audited later. It is an
    /// `Option` only so a missing value produces [`LicenceError::MissingSourceUrl`]
    /// instead of an opaque serde error.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source_url: Option<String>,
}

impl LicenseInfo {
    /// Build a complete licence record.
    #[must_use]
    pub fn new(
        id: impl Into<String>,
        attribution: impl Into<String>,
        data_commercial_use: bool,
        source_url: impl Into<String>,
    ) -> Self {
        Self {
            id: id.into(),
            attribution: attribution.into(),
            data_commercial_use,
            source_url: Some(source_url.into()),
        }
    }

    /// Validate that the record is complete enough to ingest or publish.
    pub fn validate(&self) -> Result<(), LicenceError> {
        let id = self.id.trim();
        if id.is_empty() {
            return Err(LicenceError::EmptyId);
        }
        if !KNOWN_LICENCES.contains(&id) {
            return Err(LicenceError::UnknownId(id.to_string()));
        }
        if self.attribution.trim().is_empty() {
            return Err(LicenceError::EmptyAttribution);
        }
        let Some(url) = self.source_url.as_deref().map(str::trim) else {
            return Err(LicenceError::MissingSourceUrl);
        };
        if !(url.starts_with("https://") || url.starts_with("http://"))
            || url.chars().any(char::is_whitespace)
        {
            return Err(LicenceError::InvalidSourceUrl(url.to_string()));
        }
        Ok(())
    }

    /// Whether this is an allowed licence for shipped scenario data.
    #[must_use]
    pub fn is_allowed_data_licence(&self) -> bool {
        allowed_data_licence(&self.id)
    }
}

/// Whether `id` is on the pack data-licence allowlist.
#[must_use]
pub fn allowed_data_licence(id: &str) -> bool {
    ALLOWED_DATA_LICENCES.contains(&id.trim())
}

/// Logical AND of every contributing agent's `data_commercial_use` flag.
///
/// An empty iterator is `false`: a pack with no recorded contributor does not
/// get a commercial grant by accident.
#[must_use]
pub fn data_commercial_use_all<'a>(licences: impl IntoIterator<Item = &'a LicenseInfo>) -> bool {
    let mut seen = false;
    for licence in licences {
        seen = true;
        if !licence.data_commercial_use {
            return false;
        }
    }
    seen
}

/// Typed licence rejection.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum LicenceError {
    #[error("licence id is empty")]
    EmptyId,
    #[error("licence `{0}` is not on the miner's allowlist")]
    UnknownId(String),
    #[error("licence attribution is empty")]
    EmptyAttribution,
    #[error("licence source URL is missing")]
    MissingSourceUrl,
    #[error("licence source URL `{0}` is not an http(s) URL")]
    InvalidSourceUrl(String),
}

#[cfg(test)]
mod tests {
    use super::*;

    fn valid(id: &str, commercial: bool) -> LicenseInfo {
        LicenseInfo::new(
            id,
            "Mortal 298k checkpoint (AGPL-3.0), generated by riichiprac-corpus",
            commercial,
            "https://example.invalid/licence",
        )
    }

    #[test]
    fn valid_licences_pass() {
        for id in ["CC-BY-4.0", "CC0-1.0", "MIT", "AGPL-3.0", "akochan-custom"] {
            valid(id, true)
                .validate()
                .unwrap_or_else(|err| panic!("{id} should validate: {err}"));
        }
    }

    #[test]
    fn unknown_and_incomplete_licences_fail_closed() {
        let mut unknown = valid("CC-BY-4.0", true);
        unknown.id = "public-internet".to_string();
        assert_eq!(
            unknown.validate(),
            Err(LicenceError::UnknownId("public-internet".to_string()))
        );

        let mut no_attribution = valid("MIT", true);
        no_attribution.attribution = "   ".to_string();
        assert_eq!(
            no_attribution.validate(),
            Err(LicenceError::EmptyAttribution)
        );

        let mut no_url = valid("MIT", true);
        no_url.source_url = None;
        assert_eq!(no_url.validate(), Err(LicenceError::MissingSourceUrl));

        let mut bad_url = valid("MIT", true);
        bad_url.source_url = Some("ftp://example.invalid/licence".to_string());
        assert_eq!(
            bad_url.validate(),
            Err(LicenceError::InvalidSourceUrl(
                "ftp://example.invalid/licence".to_string()
            ))
        );
    }

    #[test]
    fn data_licence_allowlist_is_separate_from_engine_licences() {
        for id in ALLOWED_DATA_LICENCES {
            assert!(allowed_data_licence(id), "{id} should be allowed data");
        }
        assert!(!allowed_data_licence("AGPL-3.0"));
        assert!(!allowed_data_licence("akochan-custom"));
        assert!(!allowed_data_licence("unknown"));
        assert!(!valid("AGPL-3.0", true).is_allowed_data_licence());
    }

    #[test]
    fn commercial_use_is_the_logical_and_of_contributors() {
        let commercial = valid("CC-BY-4.0", true);
        let non_commercial = valid("akochan-custom", false);

        assert!(data_commercial_use_all([&commercial]));
        assert!(!data_commercial_use_all([&commercial, &non_commercial]));
        assert!(!data_commercial_use_all([&non_commercial, &commercial]));
        assert!(
            !data_commercial_use_all(std::iter::empty()),
            "no contributor must not grant commercial use"
        );
    }

    #[test]
    fn licence_round_trips_through_json() {
        let info = valid("AGPL-3.0", true);
        let json = serde_json::to_string(&info).expect("serialize");
        let parsed: LicenseInfo = serde_json::from_str(&json).expect("deserialize");
        assert_eq!(parsed, info);
    }
}
