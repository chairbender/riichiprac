//! The built-in fixture pack and its provenance rows.
//!
//! P1a ships no real corpus pack. The fixture is a complete, audited pack built
//! from two existing lesson generators plus two synthetic-but-valid
//! [`GameProvenance`] rows. It exercises every document field the real publisher
//! will use (source union, licences, answers, state validation) without a
//! corpus, a model or a network.
//!
//! The fixture is deliberately honest about what it is not:
//!
//! - the states are generated, not walked from a replay, so
//!   `validation.replay_roundtrip` is false and there is no `played` action;
//! - there is no precomputed Mortal label, so the pack reports
//!   `requires_model = true`;
//! - `generator.commit` is `fixture`, never a fake git sha.
//!
//! Generation is seeded, so a test run is reproducible on the same thread.

