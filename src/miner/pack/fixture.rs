/// Id of the built-in fixture pack.
pub const FIXTURE_PACK_ID: &str = "replay.fixture.2026-11";

/// Corpus id the fixture provenance rows declare.
pub const FIXTURE_CORPUS_ID: &str = "fixture-corpus";

/// Seed for the fixture state generators.
const FIXTURE_SEED: u64 = 0x5eed_2026;

/// The two lessons the fixture pack ships, in order.
const FIXTURE_LESSONS: [ScenarioId; 2] = [ScenarioId::RyanmenProtorun, ScenarioId::FoldToRiichi];

/// Two structurally valid game rows covering both contributor kinds.
///
/// Game 0 is a four-seat Mortal mirror; game 1 mixes Mortal with the
/// project's own heuristics, so the pack's agent union has two entries and the
/// cross-engine flag is exercised.
#[must_use]
pub fn fixture_games() -> Vec<GameProvenance> {
    vec![
        fixture_game(
            0,
            "mortal_mirror",
            (0..4).map(mortal_agent).collect(),
            false,
        ),
        fixture_game(
            1,
            "rule_baseline",
            vec![
                mortal_agent(0),
                heuristic_agent(1),
                mortal_agent(2),
                heuristic_agent(3),
            ],
            true,
        ),
    ]
}

/// Build the fixture pack at `generated_at` (ISO-8601).
pub fn fixture_pack(generated_at: &str) -> Result<Pack, PackError> {
    let games = fixture_games();
    let mut scenarios = Vec::with_capacity(FIXTURE_LESSONS.len());
    for (index, lesson) in FIXTURE_LESSONS.iter().enumerate() {
        let replay = &games[index % games.len()];
        scenarios.push(fixture_scenario(*lesson, index, replay)?);
    }

    Ok(Pack {
        schema: super::model::PACK_SCHEMA.to_string(),
        version: super::model::PACK_VERSION,
        pack_id: PackId::parse(FIXTURE_PACK_ID).expect("fixture pack id is a slug"),
        generated_at: generated_at.to_string(),
        generator: PackGenerator::mine_replays("fixture", CLASSIFIER_VERSION),
        source: PackSource {
            kind: SourceKind::ai_selfplay(),
            corpus_id: CorpusId::parse(FIXTURE_CORPUS_ID).expect("fixture corpus id is a slug"),
            licence: "CC-BY-4.0".to_string(),
            attribution: "Fixture pack generated by the riichiprac miner. \
                          Games use Mortal 298k (AGPL-3.0) and the riichiprac \
                          reference heuristics (AGPL-3.0-or-later). Pack data CC BY 4.0."
                .to_string(),
            redistributable: true,
            data_commercial_use: true,
            agents: agent_union(&games),
        },
        scenarios,
    })
}

/// The fixture pack generated at the current time.
pub fn fixture_pack_now() -> Result<Pack, PackError> {
    fixture_pack(&storage::utc_iso8601(SystemTime::now()))
}

fn fixture_scenario(
    lesson: ScenarioId,
    index: usize,
    replay: &GameProvenance,
) -> Result<PackScenario, PackError> {
    // Seed before each draw so a rerun on the same thread is reproducible.
    crate::rng::seed(FIXTURE_SEED + index as u64);
    let state = crate::generator::generate_puzzle(lesson.as_str()).map_err(|detail| {
        PackError::Invalid {
            pack_id: FIXTURE_PACK_ID.to_string(),
            detail: format!(
                "cannot generate fixture lesson `{}`: {detail}",
                lesson.as_str()
            ),
        }
    })?;
    let meta = SCENARIO_MANIFEST
        .iter()
        .find(|meta| meta.id == lesson)
        .expect("every fixture lesson is in the scenario manifest");
    let accepted = accepted_for(&state);
    let book = meta.book.map(|book| PackBook {
        chapter: book.chapter,
        section: book.section,
        key: book.key(),
        label: book.label(),
    });

    Ok(PackScenario {
        id: ScenarioKey::parse(&format!("fixture-{}", lesson.as_str()))
            .expect("fixture scenario id is a slug"),
        lesson_id: lesson.as_str().to_string(),
        book,
        title: meta.label.to_string(),
        prompt: fixture_prompt(state.target_action).to_string(),
        correct_action: state.correct_action.clone(),
        accepted,
        state,
        mortal: None,
        counterfactual: None,
        played: None,
        interestingness: None,
        provenance: PackProvenance {
            replay_id: replay.replay_id.clone(),
            decision_index: index as u64,
            kyoku: Some("E1".to_string()),
            honba: Some(0),
            turn: Some(1),
            transforms: Vec::new(),
            transform_seed: None,
            variant_of: None,
            transform_chain: None,
            label_check: None,
        },
        validation: PackValidation::fixture(),
    })
}

/// An answer-free prompt for the lesson's decision kind.
fn fixture_prompt(target: TargetAction) -> &'static str {
    match target {
        TargetAction::Riichi | TargetAction::Dama => "Declare riichi, or stay in dama?",
        TargetAction::Push | TargetAction::Fold | TargetAction::Defend => {
            "Which tile do you discard?"
        }
        TargetAction::Kan => "Call the kan, or discard?",
        TargetAction::Call => "Take the offered call, or pass?",
        TargetAction::NaniKiru | TargetAction::Best => "Choose the correct action.",
    }
}

fn agent_union(games: &[GameProvenance]) -> Vec<PackAgent> {
    let mut union: std::collections::BTreeMap<String, PackAgent> =
        std::collections::BTreeMap::new();
    for game in games {
        for seat in &game.seats {
            union
                .entry(agent_key(
                    &seat.agent_id,
                    &seat.engine,
                    &seat.engine_version,
                ))
                .or_insert_with(|| PackAgent::from_spec(seat));
        }
    }
    union.into_values().collect()
}

fn fixture_game(
    index: u32,
    family: &str,
    seats: Vec<AgentSpec>,
    cross_engine: bool,
) -> GameProvenance {
    let replay_id = ReplayId::from_bytes(format!("riichiprac fixture game {index}").as_bytes());
    let log_path = DataRoot::replay_relative_path(family, &replay_id)
        .expect("fixture family and replay id build a log path");
    GameProvenance {
        schema: crate::miner::CORPUS_GAME_SCHEMA.to_string(),
        version: crate::miner::JSON_SCHEMA_VERSION,
        replay_id: replay_id.clone(),
        corpus_id: CorpusId::parse(FIXTURE_CORPUS_ID).expect("fixture corpus id"),
        family: family.to_string(),
        match_plan_id: MatchPlanId::parse("fixture-match-plan").expect("fixture plan id"),
        match_plan_sha256: sha256_hex(b"fixture match plan"),
        source: SourceKind::ai_selfplay(),
        rule: RuleProfile::tenhou_4p_hanchan(sha256_hex(b"fixture rules"), [10, 5, -5, -10]),
        generated_at: "2026-11-16T00:00:00Z".to_string(),
        generator: GeneratorInfo {
            repo: "riichiprac-corpus".to_string(),
            version: "0.1.0".to_string(),
            commit: "fixture".to_string(),
        },
        game_seed: format!("0x{index:04x}"),
        seat_schedule: "rotate_each_game".to_string(),
        seats,
        log: LogRef {
            format: "mjai".to_string(),
            path: log_path,
            bytes: 4096,
            sha256: replay_id,
        },
        validation: ValidationSummary {
            status: ValidationStatus::Ok,
            events: 100,
            tile_ledger: true,
            score_ledger: true,
            rule_profile_match: true,
        },
        cross_engine,
        policy_variety: None,
    }
}

fn mortal_agent(seat: u8) -> AgentSpec {
    AgentSpec {
        seat,
        agent_id: "mortal-298k".to_string(),
        kind: AgentKind::Neural,
        engine: "libriichi".to_string(),
        engine_version: "0.4.0".to_string(),
        engine_sha256: Some(sha256_hex(b"libriichi-0.4.0")),
        weights_sha256: Some(sha256_hex(b"mortal_298k.safetensors")),
        config: serde_json::json!({
            "boltzmann_epsilon": 0.05,
            "boltzmann_temp": 1.0,
            "top_p": 1.0
        }),
        config_hash: sha256_hex(b"fixture mortal config"),
        temperature: Some(1.0),
        sampling: "boltzmann_epsilon".to_string(),
        seed: Some(format!("0x{seat:02x}")),
        reproducible: true,
        licence: LicenseInfo::new(
            "AGPL-3.0",
            "Mortal 298k checkpoint (Equim-chan/Mortal, AGPL-3.0); game data generated by riichiprac",
            true,
            "https://github.com/Equim-chan/Mortal",
        ),
    }
}

