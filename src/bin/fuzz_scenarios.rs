//! Offline scenario fuzz runner.
//!
//! Generates real scenario puzzles, evaluates each one with the local Mortal
//! checkpoint, and writes a standard `riichiprac.scenario-report` file for every
//! case where Mortal's top action disagrees with the generator's expected
//! answer. See `scenario-fuzz-plan.md` for the design and comparison rules.
//!
//! ```bash
//! cargo run --release --bin fuzz_scenarios -- --iterations 200 --limit 20
//! cargo run --release --bin fuzz_scenarios -- --scenario shouminkan_decision --include-incomparable
//! ```
//!
//! Progress and diagnostics always go to stderr, so `--json` keeps stdout
//! parseable. Exit codes: 0 normal, 2 bad arguments or missing weights, 3 fatal
//! model/generation failure.

use std::path::{Path, PathBuf};
use std::process::ExitCode;
use std::time::{SystemTime, UNIX_EPOCH};

use candle_core::{DType, Device};
use candle_nn::VarBuilder;

use riichiprac::ai::model::MortalV4Model;
use riichiprac::ai::wasm_bridge::{Evaluation, evaluate_state, legal_action_mask};
use riichiprac::fuzz::{
    Comparison, DiscrepancyKind, FuzzOutcome, FuzzSummary, compare_action_set, file_stamp_utc,
    format_rfc3339, hex_id_from_seed, provenance_note, reported_action_for_ai,
};
use riichiprac::generator::{SCENARIO_MANIFEST, ScenarioId, generate_puzzle};
use riichiprac::report::{
    BuildReportRequest, ReportReason, ReportedAction, ReportedAi, build_report,
};
use riichiprac::rng;
use riichiprac::state::{CorrectActionType, GameState};

const DEFAULT_ITERATIONS: u64 = 200;
const DEFAULT_LIMIT: usize = 20;

/// Scenarios sampled when no `--scenario` flag is given.
///
/// `ai_best_action` is left out because it is generated by the evaluator with
/// the loaded Mortal model, so `generate_puzzle` always rejects it and every
/// attempt would be wasted.
///
/// The Added Kan lesson mixes both answers: Mortal agrees with the Kan half but
/// disagrees with the book's decline half in almost every hand. The default
/// sample skips those known-divergence hands (see [`known_divergence`]) so they
/// do not bury unknown disagreements; name `shouminkan_decision` explicitly to
/// fuzz both halves.
const DEFAULT_SCENARIOS: &[ScenarioId] = &[
    ScenarioId::RyanmenProtorun,
    ScenarioId::NakabukureReady,
    ScenarioId::ProtorunPriority,
    ScenarioId::RyankanBreak,
    ScenarioId::ChiitoitsuRiichiVsDama,
    ScenarioId::RiichiJudgement,
    ScenarioId::ShouminkanDecision,
];

/// True when the scenario cannot be generated by `generate_puzzle` alone.
fn requires_model(scenario: ScenarioId) -> bool {
    SCENARIO_MANIFEST
        .iter()
        .any(|meta| meta.id == scenario && meta.requires_ai)
}

/// True for the documented Mortal divergence in the merged Added Kan lesson.
///
/// Riichi Book 1, ch. 9 keeps the Pon and discards the drawn fourth tile in the
/// 2-away-with-value case, while Mortal favors the Kan in nearly every such
/// hand. That difference is expected and written up in
/// `scenario-fuzz-findings.md`; the default sample leaves it out.
fn known_divergence(state: &GameState) -> bool {
    state.category == ScenarioId::ShouminkanDecision.as_str()
        && state.correct_action.action_type() == CorrectActionType::Discard
}

const USAGE: &str = "\
usage: fuzz_scenarios [options]

  --scenario <id>          scenario to sample; repeatable
                           (default: ryanmen_protorun, nakabukure_ready,
                           protorun_priority, ryankan_break,
                           chiitoitsu_riichi_vs_dama, riichi_judgement,
                           shouminkan_decision;
                           ai_best_action needs the model and is rejected)
  --iterations <n>         maximum generation attempts (default: 200)
  --limit <n>              maximum discrepancy files per run (default: 20)
  --min-margin <p>         skip disagreements where Mortal's lead over the app
                           answer is smaller than p (default: 0, keep all)
  --out <dir>              report directory (default: <repo>/fuzz-reports)
  --weights <path>         Mortal checkpoint
                           (default: <repo>/frontend/public/models/mortal_298k.safetensors)
  --include-incomparable   also export expected actions with no legal Mortal
                           equivalent (Kan)
  --json                   print the summary as JSON on stdout
  --help                   show this message
";

struct Args {
    scenarios: Vec<ScenarioId>,
    /// True when `--scenario` named at least one scenario, so known divergences
    /// are sampled instead of skipped.
    explicit_scenarios: bool,
    iterations: u64,
    limit: usize,
    min_margin: f32,
    out: PathBuf,
    weights: PathBuf,
    include_incomparable: bool,
    json: bool,
}

struct ReportIdentity {
    created_at: String,
    file_stamp: String,
    id: String,
}

fn main() -> ExitCode {
    if std::env::args().any(|arg| arg == "--help" || arg == "-h") {
        print!("{USAGE}");
        return ExitCode::SUCCESS;
    }

    let args = match parse_args(std::env::args().skip(1)) {
        Ok(args) => args,
        Err(message) => {
            eprintln!("fuzz_scenarios: {message}");
            eprint!("{USAGE}");
            return ExitCode::from(2);
        }
    };

    if !args.weights.is_file() {
        eprintln!(
            "fuzz_scenarios: weights file not found: {}",
            args.weights.display()
        );
        return ExitCode::from(2);
    }

    let model = match load_model(&args.weights) {
        Ok(model) => model,
        Err(message) => {
            eprintln!("fuzz_scenarios: {message}");
            return ExitCode::from(3);
        }
    };

    let summary = match run(&args, &model) {
        Ok(summary) => summary,
        Err(message) => {
            eprintln!("fuzz_scenarios: {message}");
            return ExitCode::from(3);
        }
    };

    if args.json {
        match serde_json::to_string_pretty(&summary) {
            Ok(json) => println!("{json}"),
            Err(err) => {
                eprintln!("fuzz_scenarios: failed to serialize summary: {err}");
                return ExitCode::from(3);
            }
        }
    } else {
        print_summary(&summary);
    }

    if summary.requested_iterations > 0
        && summary.evaluations == 0
        && summary.generator_failures == summary.iterations
    {
        eprintln!(
            "fuzz_scenarios: every one of the {} generation attempts failed",
            summary.iterations
        );
        return ExitCode::from(3);
    }

    ExitCode::SUCCESS
}

fn parse_args<I: Iterator<Item = String>>(args: I) -> Result<Args, String> {
    let repo = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let mut scenarios = Vec::new();
    let mut explicit_scenarios = false;
    let mut iterations = DEFAULT_ITERATIONS;
    let mut limit = DEFAULT_LIMIT;
    let mut min_margin = 0.0f32;
    let mut out = repo.join("fuzz-reports");
    let mut weights = repo.join("frontend/public/models/mortal_298k.safetensors");
    let mut include_incomparable = false;
    let mut json = false;

    let mut args = args.peekable();
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--scenario" => {
                let value = args
                    .next()
                    .ok_or_else(|| "--scenario requires an id".to_string())?;
                let scenario = ScenarioId::from_id(&value)
                    .ok_or_else(|| format!("unknown scenario '{value}'"))?;
                if requires_model(scenario) {
                    return Err(format!(
                        "scenario '{value}' needs the Mortal model and cannot be fuzzed \
                         offline; it is generated through the evaluator"
                    ));
                }
                if !scenarios.contains(&scenario) {
                    scenarios.push(scenario);
                }
                explicit_scenarios = true;
            }
            "--iterations" => {
                let value = args
                    .next()
                    .ok_or_else(|| "--iterations requires a number".to_string())?;
                iterations = value
                    .parse()
                    .map_err(|err| format!("invalid --iterations '{value}': {err}"))?;
            }
            "--limit" => {
                let value = args
                    .next()
                    .ok_or_else(|| "--limit requires a number".to_string())?;
                limit = value
                    .parse()
                    .map_err(|err| format!("invalid --limit '{value}': {err}"))?;
            }
            "--min-margin" => {
                let value = args
                    .next()
                    .ok_or_else(|| "--min-margin requires a number".to_string())?;
                let parsed: f32 = value
                    .parse()
                    .map_err(|err| format!("invalid --min-margin '{value}': {err}"))?;
                if !parsed.is_finite() || !(0.0..=1.0).contains(&parsed) {
                    return Err(format!("--min-margin must be between 0 and 1, got {value}"));
                }
                min_margin = parsed;
            }
            "--out" => {
                out = PathBuf::from(
                    args.next()
                        .ok_or_else(|| "--out requires a directory".to_string())?,
                );
            }
            "--weights" => {
                weights = PathBuf::from(
                    args.next()
                        .ok_or_else(|| "--weights requires a path".to_string())?,
                );
            }
            "--include-incomparable" => include_incomparable = true,
            "--json" => json = true,
            other => return Err(format!("unknown option '{other}'")),
        }
    }

    if scenarios.is_empty() {
        scenarios.extend_from_slice(DEFAULT_SCENARIOS);
    }

    Ok(Args {
        scenarios,
        explicit_scenarios,
        iterations,
        limit,
        min_margin,
        out,
        weights,
        include_incomparable,
        json,
    })
}

fn load_model(path: &Path) -> Result<MortalV4Model, String> {
    let bytes = std::fs::read(path)
        .map_err(|err| format!("cannot read weights {}: {err}", path.display()))?;
    let var_builder = VarBuilder::from_buffered_safetensors(bytes, DType::F32, &Device::Cpu)
        .map_err(|err| format!("cannot parse model weights: {err}"))?;
    MortalV4Model::new(var_builder).map_err(|err| format!("cannot bind model weights: {err}"))
}

fn run(args: &Args, model: &MortalV4Model) -> Result<FuzzSummary, String> {
    std::fs::create_dir_all(&args.out)
        .map_err(|err| format!("cannot create {}: {err}", args.out.display()))?;

    let model_name = args
        .weights
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("model.safetensors")
        .to_string();

    let mut summary = FuzzSummary {
        requested_iterations: args.iterations,
        limit: args.limit,
        min_margin: args.min_margin,
        out_dir: args.out.display().to_string(),
        ..FuzzSummary::default()
    };

    if args.limit == 0 {
        summary.limit_reached = true;
        eprintln!("fuzz_scenarios: --limit 0, nothing to do");
        return Ok(summary);
    }

    eprintln!(
        "fuzz_scenarios: {} scenario(s), {} iteration(s), limit {}, out {}",
        args.scenarios.len(),
        args.iterations,
        args.limit,
        args.out.display()
    );

    let mut report_counter = 0u64;

    for iteration in 1..=args.iterations {
        summary.iterations += 1;
        let scenario = args.scenarios[rng::gen_range(0, args.scenarios.len())];
        let scenario_id = scenario.as_str();

        let state = match generate_puzzle(scenario_id) {
            Ok(state) => state,
            Err(error) => {
                summary.generator_failures += 1;
                eprintln!(
                    "[{iteration}/{}] {scenario_id}: generator rejected the state: {error}",
                    args.iterations
                );
                continue;
            }
        };

        if !args.explicit_scenarios && known_divergence(&state) {
            eprintln!(
                "[{iteration}/{}] {scenario_id}: skip known decline-half divergence \
                 (pass --scenario {scenario_id} to include it)",
                args.iterations
            );
            continue;
        }

        let evaluation = evaluate_state(model, &state)
            .map_err(|err| format!("evaluation failed for {scenario_id}: {err}"))?;
        summary.evaluations += 1;

        let legal = legal_action_mask(&state);
        let comparison = compare_action_set(
            &state.correct_action,
            &state.equivalent_tiles,
            &evaluation,
            &legal,
        );

        match comparison.outcome {
            FuzzOutcome::Agrees => {
                summary.agreements += 1;
                eprintln!(
                    "[{iteration}/{}] {scenario_id}: agree (app {} p={:.2}, AI {} p={:.2})",
                    args.iterations,
                    comparison.app_action,
                    comparison.app_probability,
                    comparison.ai_action,
                    comparison.ai_probability
                );
                continue;
            }
            FuzzOutcome::Discrepancy => {}
            FuzzOutcome::Incomparable => {
                summary.incomparable_found += 1;
                if !args.include_incomparable {
                    summary.incomparable_skipped += 1;
                    eprintln!(
                        "[{iteration}/{}] {scenario_id}: incomparable (app {} has no legal Mortal action; AI {})",
                        args.iterations, comparison.app_action, comparison.ai_action
                    );
                    continue;
                }
            }
        }

        if !comparison.exceeds_margin(args.min_margin) {
            summary.below_margin += 1;
            eprintln!(
                "[{iteration}/{}] {scenario_id}: {} within --min-margin {:.2} (app {} p={:.2} vs AI {} p={:.2}); skipped",
                args.iterations,
                comparison.kind.unwrap_or(DiscrepancyKind::Action).as_str(),
                args.min_margin,
                comparison.app_action,
                comparison.app_probability,
                comparison.ai_action,
                comparison.ai_probability
            );
            continue;
        }

        if comparison.outcome == FuzzOutcome::Discrepancy {
            *summary
                .discrepancies
                .entry(scenario_id.to_string())
                .or_insert(0) += 1;
        }

        let Some(answer) = reported_action_for_ai(
            &comparison.ai_action,
            state.correct_action.tile().unwrap_or_default(),
            evaluation.riichi_discard.as_deref(),
        ) else {
            summary.unsupported_ai_skipped += 1;
            eprintln!(
                "[{iteration}/{}] {scenario_id}: AI action '{}' cannot be expressed as a report answer; skipped",
                args.iterations, comparison.ai_action
            );
            continue;
        };

        report_counter += 1;
        let identity = report_identity(report_counter, iteration);
        let path = write_report(
            args,
            &state,
            &evaluation,
            &comparison,
            answer,
            &model_name,
            iteration,
            &identity,
        )?;
        summary.files_written += 1;

        let reason = comparison.kind.unwrap_or(DiscrepancyKind::Action).as_str();
        eprintln!(
            "[{iteration}/{}] {scenario_id}: {reason}, wrote {}",
            args.iterations,
            path.display()
        );

        if summary.files_written as usize >= args.limit {
            summary.limit_reached = true;
            eprintln!("fuzz_scenarios: reached --limit {}, stopping", args.limit);
            break;
        }
    }

    Ok(summary)
}

#[allow(clippy::too_many_arguments)]
fn write_report(
    args: &Args,
    state: &GameState,
    evaluation: &Evaluation,
    comparison: &Comparison,
    answer: ReportedAction,
    model_name: &str,
    iteration: u64,
    identity: &ReportIdentity,
) -> Result<PathBuf, String> {
    let reason = match comparison.kind.unwrap_or(DiscrepancyKind::Action) {
        DiscrepancyKind::Action => ReportReason::ExpectedActionWrong,
        DiscrepancyKind::Tile => ReportReason::ExpectedTileWrong,
    };
    let incomparable = comparison.outcome == FuzzOutcome::Incomparable;
    let note = provenance_note(
        iteration,
        &state.category,
        model_name,
        comparison,
        incomparable,
    );

    let report = build_report(BuildReportRequest {
        table: state.clone(),
        answer,
        reason,
        note: Some(note),
        created_at: identity.created_at.clone(),
        report_id: identity.id.clone(),
        commit: None,
        build_time: None,
        ai: Some(ReportedAi {
            model: model_name.to_string(),
            evaluated_at: identity.created_at.clone(),
            evaluation: evaluation.clone(),
            comparison: None,
            peeked_before_answer: false,
        }),
    })?;

    let json = serde_json::to_string_pretty(&report)
        .map_err(|err| format!("failed to serialize report: {err}"))?;
    let short_id = &identity.id[..8];
    let filename = format!(
        "riichiprac-report-{}-{}-{short_id}.json",
        state.category, identity.file_stamp
    );
    let path = args.out.join(filename);
    std::fs::write(&path, json).map_err(|err| format!("cannot write {}: {err}", path.display()))?;

    Ok(path)
}

fn report_identity(counter: u64, iteration: u64) -> ReportIdentity {
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default();
    let seconds = now.as_secs() as i64;
    let millis = now.subsec_millis();
    let seed = (seconds as u64)
        .wrapping_mul(1_000_000_000)
        .wrapping_add(u64::from(millis))
        ^ counter.wrapping_mul(0x9e37_79b9_7f4a_7c15)
        ^ iteration;

    ReportIdentity {
        created_at: format_rfc3339(seconds, millis),
        file_stamp: file_stamp_utc(seconds),
        id: hex_id_from_seed(seed),
    }
}

fn print_summary(summary: &FuzzSummary) {
    println!("fuzz_scenarios summary");
    println!(
        "  iterations:          {} / {}",
        summary.iterations, summary.requested_iterations
    );
    println!("  generator failures:  {}", summary.generator_failures);
    println!("  evaluations:         {}", summary.evaluations);
    println!("  agreements:          {}", summary.agreements);
    if summary.discrepancies.is_empty() {
        println!("  discrepancies:       none");
    } else {
        println!("  discrepancies:");
        for (scenario, count) in &summary.discrepancies {
            println!("    {scenario}: {count}");
        }
    }
    println!(
        "  incomparable:        {} found, {} skipped",
        summary.incomparable_found, summary.incomparable_skipped
    );
    println!(
        "  unsupported AI:      {} skipped",
        summary.unsupported_ai_skipped
    );
    println!("  below --min-margin:  {}", summary.below_margin);
    println!("  files written:       {}", summary.files_written);
    println!(
        "  limit:               {}{}",
        summary.limit,
        if summary.limit_reached {
            " (reached, stopped early)"
        } else {
            ""
        }
    );
    println!("  output:              {}", summary.out_dir);
}

#[cfg(test)]
mod tests {
    use super::*;

    fn parse(values: &[&str]) -> Result<Args, String> {
        parse_args(values.iter().map(|value| (*value).to_string()))
    }

    #[test]
    fn defaults_cover_every_fuzzable_scenario() {
        let args = parse(&[]).unwrap();

        assert_eq!(args.scenarios, DEFAULT_SCENARIOS.to_vec());
        assert_eq!(
            args.scenarios,
            vec![
                ScenarioId::RyanmenProtorun,
                ScenarioId::NakabukureReady,
                ScenarioId::ProtorunPriority,
                ScenarioId::RyankanBreak,
                ScenarioId::ChiitoitsuRiichiVsDama,
                ScenarioId::RiichiJudgement,
                ScenarioId::ShouminkanDecision,
            ]
        );
        assert_eq!(args.iterations, DEFAULT_ITERATIONS);
        assert_eq!(args.limit, DEFAULT_LIMIT);
        assert!(!args.include_incomparable);
        assert!(!args.json);
        assert!(args.out.ends_with("fuzz-reports"));
    }

    #[test]
    fn model_backed_scenarios_are_never_in_the_default_set() {
        let args = parse(&[]).unwrap();

        for &scenario in ScenarioId::ALL {
            let generated = generate_puzzle(scenario.as_str());
            assert_eq!(
                generated.is_ok(),
                !requires_model(scenario),
                "{} fuzzability disagrees with the manifest",
                scenario.as_str()
            );
            if requires_model(scenario) {
                assert!(!args.scenarios.contains(&scenario));
            }
        }
    }

    #[test]
    fn explicit_scenario_selection_includes_known_divergences() {
        assert!(!parse(&[]).unwrap().explicit_scenarios);

        let args = parse(&["--scenario", "shouminkan_decision"]).unwrap();
        assert!(args.explicit_scenarios);
        assert_eq!(args.scenarios, vec![ScenarioId::ShouminkanDecision]);
    }

    #[test]
    fn known_decline_divergence_is_classified_by_answer() {
        let mut saw_kan = false;
        let mut saw_decline = false;

        for _ in 0..80 {
            let state = generate_puzzle("shouminkan_decision").expect("lesson must generate");
            match state.correct_action.action_type() {
                CorrectActionType::Kan => {
                    saw_kan = true;
                    assert!(!known_divergence(&state), "the Kan half is comparable");
                }
                CorrectActionType::Discard => {
                    saw_decline = true;
                    assert!(
                        known_divergence(&state),
                        "the discard half is the known divergence"
                    );
                }
                other => panic!("unexpected Added Kan answer {other:?}"),
            }
        }

        assert!(
            saw_kan && saw_decline,
            "the merged lesson must produce both halves"
        );
    }

    #[test]
    fn model_backed_scenario_is_rejected() {
        let err = match parse(&["--scenario", "ai_best_action"]) {
            Ok(_) => panic!("ai_best_action must be rejected"),
            Err(err) => err,
        };

        assert!(err.contains("ai_best_action"), "{err}");
        assert!(err.contains("Mortal model"), "{err}");
    }

    #[test]
    fn repeatable_scenario_flags_are_deduplicated() {
        let args = parse(&[
            "--scenario",
            "ryanmen_protorun",
            "--scenario",
            "ryanmen_protorun",
            "--scenario",
            "shouminkan_decision",
        ])
        .unwrap();

        assert_eq!(
            args.scenarios,
            vec![ScenarioId::RyanmenProtorun, ScenarioId::ShouminkanDecision]
        );
    }

    #[test]
    fn unknown_scenario_and_bad_numbers_are_rejected() {
        assert!(parse(&["--scenario", "nope"]).is_err());
        assert!(parse(&["--iterations", "many"]).is_err());
        assert!(parse(&["--limit", "-1"]).is_err());
        assert!(parse(&["--bogus"]).is_err());
    }

    #[test]
    fn min_margin_defaults_to_zero_and_accepts_probabilities() {
        assert_eq!(parse(&[]).unwrap().min_margin, 0.0);

        let args = parse(&["--min-margin", "0.05"]).unwrap();
        assert!((args.min_margin - 0.05).abs() < f32::EPSILON);
        assert_eq!(parse(&["--min-margin", "1"]).unwrap().min_margin, 1.0);

        assert!(parse(&["--min-margin", "many"]).is_err());
        assert!(parse(&["--min-margin", "-0.1"]).is_err());
        assert!(parse(&["--min-margin", "1.5"]).is_err());
        assert!(parse(&["--min-margin"]).is_err());
    }

    #[test]
    fn flags_parse() {
        let args = parse(&[
            "--iterations",
            "7",
            "--limit",
            "2",
            "--out",
            "/tmp/x",
            "--weights",
            "/tmp/w.safetensors",
            "--include-incomparable",
            "--json",
        ])
        .unwrap();

        assert_eq!(args.iterations, 7);
        assert_eq!(args.limit, 2);
        assert_eq!(args.out, PathBuf::from("/tmp/x"));
        assert_eq!(args.weights, PathBuf::from("/tmp/w.safetensors"));
        assert!(args.include_incomparable);
        assert!(args.json);
    }
}
