/**
 * The carve asset bridge, against the 3D-owned bake (3D-17).
 *
 * The Task 4B relief atlases this module originally shipped against were
 * retired from the tree on 2026-11-18 (AGENTS.md §5), so the only committed
 * source is `relief3d/` + `relief3d.json`, generated by
 * `frontend/tools/relief3d/bake-relief3d.mjs`. These tests pin that bake:
 * vocabulary, rect mapping, byte/hash pins, the carve signature the live
 * shading depends on, the loader and the truthful fallback.
 *
 * The non-colour atlases are decoded with a small straight-alpha PNG reader,
 * not a canvas: a canvas premultiplies alpha and the height channel is 0 across
 * every groove floor, so a canvas read zeroes those normals (the bug that
 * 3D-17 fixed in the runtime factory too).
 *
 * No test inspects a rendered frame (AGENTS.md §6).
 */

const tableDir = fileURLToPath(new URL('../../../public/table/', import.meta.url));

const manifestBytes = readFileSync(join(tableDir, 'relief3d.json'));
const rawManifest = JSON.parse(manifestBytes.toString('utf8')) as Record<string, unknown>;
const manifest = parseReliefManifest(rawManifest);

const MANIFEST_URL = '/table/relief3d.json';
const ATLAS_URLS = {
  face_albedo: '/table/relief3d/face_albedo.png',
  face_normal_depth: '/table/relief3d/face_normal_depth.png',
  face_ao_roughness: '/table/relief3d/face_ao_roughness.png',
} as const;

function readAtlas(key: keyof typeof ATLAS_URLS): Uint8Array {
  return readFileSync(join(tableDir, PINNED_RELIEF3D_ATLASES[key].file));
}

function fileResponse(bytes: Uint8Array): ReliefFetchResponse {
  return {
    ok: true,
    status: 200,
    async arrayBuffer() {
      return bytes.buffer.slice(
        bytes.byteOffset,
        bytes.byteOffset + bytes.byteLength,
      ) as ArrayBuffer;
    },
  };
}

/** A fetch over the committed files; any URL not in the map is a 404. */
function reliefFetch(
  overrides: Partial<Record<keyof typeof ATLAS_URLS, Uint8Array>> = {},
  includeManifest = true,
): ReliefFetch {
  const files = new Map<string, Uint8Array>();
  if (includeManifest) files.set(MANIFEST_URL, new Uint8Array(manifestBytes));
  for (const key of Object.keys(ATLAS_URLS) as (keyof typeof ATLAS_URLS)[]) {
    files.set(ATLAS_URLS[key], overrides[key] ?? new Uint8Array(readAtlas(key)));
  }
  return async (url: string) => {
    const bytes = files.get(url);
    if (!bytes) {
      return {
        ok: false,
        status: 404,
        async arrayBuffer() {
          return new ArrayBuffer(0);
        },
      };
    }
    return fileResponse(bytes);
  };
}

/** Straight-alpha PNG decode for the non-colour atlases (filter 0 only). */
function decodeStraightPng(file: string): {
  readonly width: number;
  readonly height: number;
  readonly data: Uint8ClampedArray;
} {
  const buffer = readFileSync(join(tableDir, file));
  let offset = 8;
  let width = 0;
  let height = 0;
  const idat: Buffer[] = [];
  while (offset < buffer.length) {
    const length = buffer.readUInt32BE(offset);
    const type = buffer.toString('ascii', offset + 4, offset + 8);
    const data = buffer.subarray(offset + 8, offset + 8 + length);
    if (type === 'IHDR') {
      width = data.readUInt32BE(0);
      height = data.readUInt32BE(4);
      if (data[8] !== 8 || data[9] !== 6) throw new Error('expected 8-bit RGBA');
      if (data[12] !== 0) throw new Error('expected a non-interlaced PNG');
    }
    if (type === 'IDAT') idat.push(data);
    offset += 12 + length;
  }
  const raw = inflateSync(Buffer.concat(idat));
  const stride = width * 4 + 1;
  const out = new Uint8ClampedArray(width * height * 4);
  for (let y = 0; y < height; y += 1) {
    if (raw[y * stride] !== 0) throw new Error('expected filter type 0');
    raw.copy(Buffer.from(out.buffer), y * width * 4, y * stride + 1, y * stride + 1 + width * 4);
  }
  return { width, height, data: out };
}

type AtlasPixel = {
  readonly width: number;
  readonly height: number;
  readonly data: Uint8Array | Uint8ClampedArray;
};

/** Decode the albedo (safe through a canvas: paint alpha is 0 or 255). */
async function albedoAtlas(): Promise<AtlasPixel> {
  const image = await loadNapiImage(readFileSync(join(tableDir, PINNED_RELIEF3D_ATLASES.face_albedo.file)));
  const canvas = createCanvas(image.width, image.height);
  const context = canvas.getContext('2d');
  context.drawImage(image, 0, 0);
  return {
    width: image.width,
    height: image.height,
    data: context.getImageData(0, 0, image.width, image.height).data,
  };
}

function cellOffset(face: string): { x: number; y: number } {
  const cell = manifest.cells.get(face as never);
  if (!cell) throw new Error(`no cell for ${face}`);
  return { x: cell.x, y: cell.y };
}

interface FakeTexture extends ReliefTextureHandle {
  readonly request: ReliefTextureRequest;
  disposed: number;
}

function fakeFactory(options: { throwOnCall?: number } = {}): {
  requests: ReliefTextureRequest[];
  textures: FakeTexture[];
  createTexture: { create(request: ReliefTextureRequest): FakeTexture };
} {
  const requests: ReliefTextureRequest[] = [];
  const textures: FakeTexture[] = [];
  return {
    requests,
    textures,
    createTexture: {
      create(request) {
        requests.push(request);
        if (options.throwOnCall === requests.length) {
          throw new Error('GPU is full');
        }
        const texture: FakeTexture = {
          request,
          disposed: 0,
          dispose() {
            this.disposed += 1;
          },
        };
        textures.push(texture);
        return texture;
      },
    },
  };
}

describe('relief3d manifest: the contract vocabulary', () => {
  it('pins the 37 baked face ids, in atlas order, without blank', () => {
    expect(RELIEF_FACE_IDS).toEqual(TILE_FACE_IDS.filter((face) => face !== 'blank'));
    expect(RELIEF_FACE_IDS).toHaveLength(37);
    expect(RELIEF_FACE_IDS).not.toContain('blank');
  });

  it('resolves all 37 baked faces and addresses exactly 37 of the 42 cells', () => {
    expect(manifest.cells.size).toBe(RELIEF_RASTER.faceCount);
    const used = new Set([...manifest.cells.values()].map((cell) => cell.index));
    expect(used.size).toBe(RELIEF_RASTER.faceCount);
    for (const index of used) {
      expect(index).toBeGreaterThanOrEqual(0);
      expect(index).toBeLessThan(RELIEF_RASTER.columns * RELIEF_RASTER.rows);
    }
  });

  it('maps face ids to normalized rects with a top-left origin and V down', () => {
    for (const [face, cell] of manifest.cells) {
      expect(cell.rect[0]).toBeCloseTo(cell.x / RELIEF_RASTER.atlasWidth, 6);
      expect(cell.rect[1]).toBeCloseTo(cell.y / RELIEF_RASTER.atlasHeight, 6);
      expect(cell.rect[2]).toBeCloseTo(
        (cell.x + RELIEF_RASTER.cellWidth) / RELIEF_RASTER.atlasWidth,
        6,
      );
      expect(cell.rect[3]).toBeCloseTo(
        (cell.y + RELIEF_RASTER.cellHeight) / RELIEF_RASTER.atlasHeight,
        6,
      );
      expect(face).toBe(RELIEF_FACE_IDS[cell.index]);
    }
  });

  it('pins each atlas by byte length and PNG SHA-256', () => {
    for (const key of Object.keys(PINNED_RELIEF3D_ATLASES) as (keyof typeof PINNED_RELIEF3D_ATLASES)[]) {
      const pin = PINNED_RELIEF3D_ATLASES[key];
      const bytes = readFileSync(join(tableDir, pin.file));
      expect(bytes.byteLength, key).toBe(pin.bytes);
      expect(createHash('sha256').update(bytes).digest('hex'), key).toBe(pin.sha256);
      expect(manifest.atlases[key].file).toBe(pin.file);
    }
  });

  it('maps the plate to 0.64 x 0.89 units, not the 21 x 28 mm body', () => {
    expect(RELIEF_PLATE_UNITS).toEqual([0.64, 0.89]);
    expect(TILE.facePlateWidthUnits).toBeCloseTo(RELIEF_PLATE_UNITS[0], 9);
    expect(TILE.facePlateHeightUnits).toBeCloseTo(RELIEF_PLATE_UNITS[1], 9);
    expect(manifest.plateUnits).toEqual(RELIEF_PLATE_UNITS);
  });

  it('carries the decal carve signature the live shading depends on', () => {
    const carve = rawManifest.carve as Record<string, unknown>;
    expect(carve.depthMm).toBeCloseTo(0.495, 6);
    expect(carve.transitionMm).toBeCloseTo(0.3, 6);
    expect(carve.blurMm).toBeCloseTo(0.12, 6);
    expect(carve.aoDistanceMm).toBeCloseTo(1.4, 6);
    const profile = carve.profile as Record<string, number>;
    expect(profile.topSpread).toBe(0.6);
    expect(profile.bottomSpread).toBe(0.8);
  });
});

describe('relief3d: decoded-pixel evidence', () => {
  it('leaves the artwork white uncarved and the paint carved (1p against Haku)', async () => {
    const albedo = await albedoAtlas();
    const pin = cellOffset('1p');
    const haku = cellOffset('5z');
    let paint = 0;
    let white = 0;
    for (let y = 0; y < RELIEF_RASTER.cellHeight; y += 1) {
      for (let x = 0; x < RELIEF_RASTER.cellWidth; x += 1) {
        const offset = ((pin.y + y) * albedo.width + pin.x + x) * 4;
        if (albedo.data[offset + 3] > 128) paint += 1;
        const hakuOffset = ((haku.y + y) * albedo.width + haku.x + x) * 4;
        if (albedo.data[hakuOffset + 3] > 128) white += 1;
      }
    }
    const cellArea = RELIEF_RASTER.cellWidth * RELIEF_RASTER.cellHeight;
    // 1p is woven with white that is the bare tile: only the pigment stays.
    expect(paint / cellArea).toBeCloseTo(0.396, 2);
    // Haku (5z) has no printed mark at all.
    expect(white).toBe(0);
    expect(manifest.cells.get('5z')).toBeTruthy();
  });

  it('decodes the normal atlas straight-alpha, not through a canvas', () => {
    const normal = decodeStraightPng(PINNED_RELIEF3D_ATLASES.face_normal_depth.file);
    const pin = cellOffset('1p');
    const pixel = (x: number, y: number) => {
      const offset = ((pin.y + y) * normal.width + pin.x + x) * 4;
      return [normal.data[offset], normal.data[offset + 1], normal.data[offset + 2], normal.data[offset + 3]];
    };
    // A flat groove floor keeps its normal even where the height alpha is 0 —
    // the property a canvas round-trip destroys.
    let flatWithZeroAlpha = 0;
    for (let y = 0; y < RELIEF_RASTER.cellHeight; y += 4) {
      for (let x = 0; x < RELIEF_RASTER.cellWidth; x += 4) {
        const [r, g, b, a] = pixel(x, y);
        if (a === 0 && r === 128 && g === 128 && b === 255) flatWithZeroAlpha += 1;
      }
    }
    expect(flatWithZeroAlpha).toBeGreaterThan(100);
  });
});

describe('relief3d: load', () => {
  it('creates the three textures with the committed settings and reports GPU bytes', async () => {
    const factory = fakeFactory();
    const assets = await loadReliefAssets({
      tier: 'high',
      baseUrl: '/',
      fetchImpl: reliefFetch(),
      createTexture: factory.createTexture,
    });
    expect(assets.status).toBe('relief3d');
    expect(factory.requests).toHaveLength(3);
    for (const request of factory.requests) {
      expect(request.flipY).toBe(false);
      expect(request.width).toBe(RELIEF_RASTER.atlasWidth);
      expect(request.height).toBe(RELIEF_RASTER.atlasHeight);
      expect(request.generateMipmaps).toBe(true);
    }
    const albedo = factory.requests.find((request) => request.role === 'albedo');
    const normal = factory.requests.find((request) => request.role === 'normalDepth');
    expect(albedo?.colorSpace).toBe('srgb');
    expect(normal?.colorSpace).toBe('linear');
    expect(assets.atlasBytes).toBe(reliefGpuBytes('high').total);
    // Node ships `crypto.subtle`, so this is the WebCrypto path; the two tests
    // below cover the insecure-origin fallback.
    expect(assets.verification).toBe('webcrypto');
    assets.dispose();
  });

  it('verifies with WebCrypto when it exists, and says so', async () => {
    const digest = vi.fn(async () => new ArrayBuffer(32));
    const original = Object.getOwnPropertyDescriptor(globalThis, 'crypto');
    Object.defineProperty(globalThis, 'crypto', {
      configurable: true,
      value: { subtle: { digest } },
    });
    try {
      const factory = fakeFactory();
      // The fake digest cannot match the pins, so the load must fall back — what
      // matters here is that WebCrypto was the path taken, not the JS one.
      const assets = await loadReliefAssets({
        tier: 'high',
        baseUrl: '/',
        fetchImpl: reliefFetch(),
        createTexture: factory.createTexture,
        warn: () => {},
      });
      expect(digest).toHaveBeenCalledTimes(1);
      expect(assets.status).toBe('fallback');
      expect(assets.verification).toBeNull();
      assets.dispose();
    } finally {
      if (original) Object.defineProperty(globalThis, 'crypto', original);
      else delete (globalThis as { crypto?: unknown }).crypto;
    }
  });

  it('still loads the committed carve when crypto.subtle is missing', async () => {
    // The defect: an insecure origin (plain HTTP on a LAN/tailnet address) has no
    // `crypto.subtle`, and the loader used to fall back to the procedural cells —
    // silently losing the art. It must now verify with the JS implementation.
    const original = Object.getOwnPropertyDescriptor(globalThis, 'crypto');
    Object.defineProperty(globalThis, 'crypto', { configurable: true, value: {} });
    const warnings: string[] = [];
    try {
      const factory = fakeFactory();
      const assets = await loadReliefAssets({
        tier: 'high',
        baseUrl: '/',
        fetchImpl: reliefFetch(),
        createTexture: factory.createTexture,
        warn: (message) => warnings.push(message),
      });
      expect(assets.status).toBe('relief3d');
      expect(assets.verification).toBe('javascript');
      expect(factory.requests).toHaveLength(3);
      // Exactly one warning, and it names the cause and the fix rather than
      // pretending the fallback is normal.
      expect(warnings).toHaveLength(1);
      expect(warnings[0]).toContain('not a secure context');
      expect(warnings[0]).toContain('HTTPS');
      assets.dispose();
    } finally {
      if (original) Object.defineProperty(globalThis, 'crypto', original);
      else delete (globalThis as { crypto?: unknown }).crypto;
    }
  });

  it('clamps anisotropy to the renderer maximum and never below 1', async () => {
    for (const [max, expected] of [
      [16, RELIEF_TIER_SETTINGS.high.anisotropy],
      [2, 2],
      [0, 1],
    ] as const) {
      const factory = fakeFactory();
      const assets = await loadReliefAssets({
        tier: 'high',
        baseUrl: '/',
        maxAnisotropy: max,
        fetchImpl: reliefFetch(),
        createTexture: factory.createTexture,
      });
      for (const request of factory.requests) expect(request.anisotropy).toBe(expected);
      assets.dispose();
    }
  });

  it('halves each atlas axis and the GPU bytes at the compat tier', async () => {
    expect(reliefTextureSize('compat')).toEqual({ width: 768, height: 1190 });
    // 3D-11: the upload scale only changes at compat, so a high <-> balanced
    // downgrade never re-decodes the atlases.
    expect(reliefUploadScale('high')).toBe(1);
    expect(reliefUploadScale('balanced')).toBe(1);
    expect(reliefUploadScale('compat')).toBe(0.5);
    const factory = fakeFactory();
    const assets = await loadReliefAssets({
      tier: 'compat',
      baseUrl: '/',
      fetchImpl: reliefFetch(),
      createTexture: factory.createTexture,
    });
    for (const request of factory.requests) {
      expect(request.width).toBe(768);
      expect(request.height).toBe(1190);
    }
    expect(assets.atlasBytes).toBe(reliefGpuBytes('compat').total);
    expect(reliefGpuBytes('compat').total).toBeLessThan(reliefGpuBytes('high').total / 3);
    assets.dispose();
  });
});

describe('relief3d: the truthful fallback path', () => {
  it('uses the neutral cell when the manifest is missing, with one warning', async () => {
    const warn = vi.fn();
    const factory = fakeFactory();
    const assets = await loadReliefAssets({
      tier: 'high',
      baseUrl: '/',
      fetchImpl: reliefFetch({}, false),
      createTexture: factory.createTexture,
      warn,
    });
    expect(assets.status).toBe('fallback');
    expect(warn).toHaveBeenCalledTimes(1);
    expect(warn.mock.calls[0][0]).toMatch(/manifest-fetch/);
    expect(factory.requests).toHaveLength(3);
    expect(factory.requests.every((request) => request.pixels !== null)).toBe(true);
    const bytes = reliefTextureBytes(
      NEUTRAL_CELL_SIZE,
      NEUTRAL_CELL_SIZE,
      RELIEF_TIER_SETTINGS.high.mipmaps,
    );
    expect(assets.atlasBytes).toBe(bytes * 3);
    for (const face of RELIEF_FACE_IDS) {
      expect(assets.cellForFace(face)?.rect).toEqual([0, 0, 1, 1]);
    }
    assets.dispose();
  });

  it('falls back on an atlas hash mismatch without creating committed textures', async () => {
    const warn = vi.fn();
    const factory = fakeFactory();
    const corrupted = new Uint8Array(readAtlas('face_normal_depth'));
    corrupted[corrupted.length - 1] ^= 0xff;
    const assets = await loadReliefAssets({
      tier: 'high',
      baseUrl: '/',
      fetchImpl: reliefFetch({ face_normal_depth: corrupted }),
      createTexture: factory.createTexture,
      warn,
    });
    expect(assets.status).toBe('fallback');
    expect(warn).toHaveBeenCalledTimes(1);
    expect(warn.mock.calls[0][0]).toMatch(/sha256|hash/);
    expect(factory.requests.every((request) => request.pixels !== null)).toBe(true);
    assets.dispose();
  });

  it('falls back on a manifest version bump', async () => {
    const warn = vi.fn();
    const factory = fakeFactory();
    const bumped = { ...rawManifest, version: 99 };
    const fetchImpl: ReliefFetch = async (url) =>
      url === MANIFEST_URL
        ? fileResponse(new Uint8Array(Buffer.from(JSON.stringify(bumped))))
        : reliefFetch()(url);
    const assets = await loadReliefAssets({
      tier: 'high',
      baseUrl: '/',
      fetchImpl,
      createTexture: factory.createTexture,
      warn,
    });
    expect(assets.status).toBe('fallback');
    expect(warn.mock.calls[0][0]).toMatch(/manifest-version/);
    assets.dispose();
  });

  it('reports a texture failure once and still installs the fallback', async () => {
    const warn = vi.fn();
    const factory = fakeFactory({ throwOnCall: 2 });
    const assets = await loadReliefAssets({
      tier: 'high',
      baseUrl: '/',
      fetchImpl: reliefFetch(),
      createTexture: factory.createTexture,
      warn,
    });
    expect(assets.status).toBe('fallback');
    expect(warn).toHaveBeenCalledTimes(1);
    expect(warn.mock.calls[0][0]).toMatch(/texture/);
    // The one texture the failed committed attempt created was disposed; the
    // three of the fallback are live until the assets are disposed.
    expect(factory.textures[0].disposed).toBe(1);
    expect(factory.textures).toHaveLength(1 + 3);
    expect(factory.textures.slice(1).every((texture) => texture.disposed === 0)).toBe(true);
    assets.dispose();
  });

  it('builds the neutral channels with the committed values', () => {
    const albedo = buildNeutralCell('albedo');
    expect([...albedo.data.slice(0, 4)]).toEqual([255, 255, 255, 0]);
    const normal = buildNeutralCell('normalDepth');
    expect([...normal.data.slice(0, 4)]).toEqual([128, 128, 255, 255]);
    const ao = buildNeutralCell('aoRoughness');
    expect([...ao.data.slice(0, 4)]).toEqual([255, 115, 0, 255]);
  });

  it('rejects a non-normalized or off-cell rect', () => {
    const broken = JSON.parse(JSON.stringify(rawManifest)) as Record<string, unknown>;
    const faces = broken.faces as Record<string, { cell: { rect: number[] } }>;
    faces['1m'].cell.rect = [0, 0, 2, 0.14];
    expect(() => parseReliefManifest(broken)).toThrow(ReliefAssetError);
  });
});

