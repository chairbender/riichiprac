#!/usr/bin/env python3
"""Reference implementation of Mortal v4 used to generate the Candle parity fixture.

The Rust port in ``src/ai/model.rs`` is validated against PyTorch: this script
rebuilds the network exactly as ``Equim-chan/Mortal``'s ``mortal/model.py`` does
(version 4), loads ``VoidShine/mortal-298k`` into it, runs one deterministic
observation through the encoder + DQN head, and stores the 47 outputs in
``tests/fixtures/mortal_v4_parity.json``.

The input is generated by a 32-bit LCG so that Rust can reproduce it bit for bit:

    state = (1664525 * state + 1013904223) mod 2^32   (seed 0x1234ABCD)
    value = (state >> 8) / 2^23 - 1.0                 (exact in f32, range [-1, 1))

Run after ``scripts/convert_weights.py`` has populated the weight cache:

    .venv/bin/python scripts/mortal_reference.py
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

INPUT_CHANNELS = 1012
TILE_FEATURES = 34
SEED = 0x1234ABCD
LCG_MULTIPLIER = 1664525
LCG_INCREMENT = 1013904223

FIXTURE_PATH = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "mortal_v4_parity.json"
CHECKPOINT_PATH = Path(__file__).resolve().parents[1] / "scripts" / ".weights-cache" / "mortal_298k.pth"


def build_input() -> list[float]:
    """Same values ``model_test.rs`` builds in Rust."""
    state = SEED
    values = []
    for _ in range(INPUT_CHANNELS * TILE_FEATURES):
        state = (LCG_MULTIPLIER * state + LCG_INCREMENT) & 0xFFFFFFFF
        values.append((state >> 8) / 8388608.0 - 1.0)
    return values


def build_modules():
    import torch
    from torch import nn

    class ChannelAttention(nn.Module):
        def __init__(self, channels, ratio=16):
            super().__init__()
            self.shared_mlp = nn.Sequential(
                nn.Linear(channels, channels // ratio, bias=True),
                nn.Mish(inplace=True),
                nn.Linear(channels // ratio, channels, bias=True),
            )

        def forward(self, x):
            avg_out = self.shared_mlp(x.mean(-1))
            max_out = self.shared_mlp(x.amax(-1))
            return (avg_out + max_out).sigmoid().unsqueeze(-1) * x

    class ResBlock(nn.Module):
        """Pre-activation block (``pre_actv=True`` in Mortal)."""

        def __init__(self, channels, norm_builder, actv_builder):
            super().__init__()
            self.res_unit = nn.Sequential(
                norm_builder(),
                actv_builder(),
                nn.Conv1d(channels, channels, kernel_size=3, padding=1, bias=False),
                norm_builder(),
                actv_builder(),
                nn.Conv1d(channels, channels, kernel_size=3, padding=1, bias=False),
            )
            self.ca = ChannelAttention(channels)

        def forward(self, x):
            out = self.res_unit(x)
            out = self.ca(out)
            return out + x

    class ResNet(nn.Module):
        def __init__(self, in_channels, conv_channels, num_blocks, norm_builder, actv_builder):
            super().__init__()
            layers = [nn.Conv1d(in_channels, conv_channels, kernel_size=3, padding=1, bias=False)]
            layers += [ResBlock(conv_channels, norm_builder, actv_builder) for _ in range(num_blocks)]
            layers += [
                norm_builder(),
                actv_builder(),
                nn.Conv1d(conv_channels, 32, kernel_size=3, padding=1),
                actv_builder(),
                nn.Flatten(),
                nn.Linear(32 * 34, 1024),
            ]
            self.net = nn.Sequential(*layers)

        def forward(self, x):
            return self.net(x)

    class Brain(nn.Module):
        def __init__(self, conv_channels, num_blocks, version=4):
            super().__init__()
            self.version = version
            in_channels = {4: 1012}[version]
            norm_builder = lambda: nn.BatchNorm1d(conv_channels, momentum=0.01, eps=1e-3)
            actv_builder = lambda: nn.Mish(inplace=True)
            self.encoder = ResNet(
                in_channels=in_channels,
                conv_channels=conv_channels,
                num_blocks=num_blocks,
                norm_builder=norm_builder,
                actv_builder=actv_builder,
            )
            self.actv = actv_builder()

        def forward(self, obs):
            return self.actv(self.encoder(obs))

    class DQN(nn.Module):
        """Mortal v4 DQN: a single linear layer emitting value + action logits."""

        def __init__(self, version=4):
            super().__init__()
            self.version = version
            self.net = nn.Linear(1024, 1 + 46)
            nn.init.constant_(self.net.bias, 0)

        def forward(self, phi):
            v, a = self.net(phi).split((1, 46), dim=-1)
            return v, a

    return torch, Brain, DQN


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--checkpoint", type=Path, default=CHECKPOINT_PATH)
    parser.add_argument("--output", type=Path, default=FIXTURE_PATH)
    args = parser.parse_args()

    torch, Brain, DQN = build_modules()
    checkpoint = torch.load(args.checkpoint, map_location="cpu", weights_only=False)

    brain = Brain(conv_channels=192, num_blocks=40, version=4)
    dqn = DQN(version=4)
    brain.load_state_dict(checkpoint["mortal"], strict=True)
    dqn.load_state_dict(checkpoint["current_dqn"], strict=True)
    brain.eval()
    dqn.eval()

    observations = torch.tensor(build_input(), dtype=torch.float32).reshape(
        1, INPUT_CHANNELS, TILE_FEATURES
    )
    with torch.no_grad():
        features = brain(observations)
        value, logits = dqn(features)
        outputs = torch.cat((value, logits), dim=-1).flatten().tolist()

    fixture = {
        "_comment": (
            "Generated by scripts/mortal_reference.py: PyTorch Mortal v4 forward pass on a "
            "deterministic LCG observation. Regenerate with that script; do not hand-edit."
        ),
        "seed": SEED,
        "input_shape": [1, INPUT_CHANNELS, TILE_FEATURES],
        "tolerance": 1e-3,
        "outputs": outputs,
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(fixture, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(outputs)} reference outputs to {args.output}")
    print("first five:", outputs[:5])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
